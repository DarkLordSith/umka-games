// Микшер: все громкости приложения в одном месте. Подкручивать — здесь, одной строкой.
// Множители амплитуды (1 = 0 dB, 0.5 ≈ −6 dB). Файлы голоса не перекодируем: громкость
// задаёт канал, поэтому будущие записи владельца зазвучат так же.
// Чистый модуль без Web Audio — его проверяют тесты.

/** Амплитуда → dB. */
export const toDb = (gain: number): number => 20 * Math.log10(gain);

export const MIX = {
  /** Голос: −6 dB (было 0 dB — владелец 21.11: слишком громко). */
  voice: 0.5,
  /** Эффекты: 0 dB. */
  sfx: 1,
  /** Музыка: тихий фон, ≈ −15 dB. */
  music: 0.17,
  /**
   * Пока звучит голос: эффекты и музыка — доля от своего уровня. Голос стал тише на 6 dB —
   * приглушение глубже на те же 6 dB, чтобы голос над фоном выделялся как раньше.
   */
  sfxUnderVoice: 0.175,
  musicUnderVoice: 0.1,
} as const;
